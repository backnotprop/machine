// Builds docs/ui-v3/prototype/data.js from the live API: every run, every machine (latest version),
// a dagre layout per machine (TB and LR), and the rendered SKILL.md. Read-only toward src/.
// Usage: bun docs/ui-v3/build-data.ts [base-url]
import dagre from "@dagrejs/dagre";
import { renderSkill } from "../../src/engine/render-skill.ts";
import type { Machine } from "../../src/engine/engine.ts";

const base = process.argv[2] ?? "http://localhost:7420";
const get = async (p: string) => (await fetch(base + p)).json();

const summaries = await get("/api/runs");
const runs = await Promise.all(summaries.map((s: { id: string }) => get(`/api/runs/${s.id}`)));
const all: Machine[] = await get("/api/machines");
const latest: Record<string, Machine> = {};
for (const m of all) if (!latest[m.id] || latest[m.id].version < m.version) latest[m.id] = m;

function layout(m: Machine, rankdir: "TB" | "LR") {
  const g = new dagre.graphlib.Graph({ multigraph: true })
    .setGraph({ rankdir, nodesep: rankdir === "TB" ? 26 : 18, ranksep: rankdir === "TB" ? 46 : 40, marginx: 12, marginy: 12, ranker: "tight-tree" })
    .setDefaultEdgeLabel(() => ({}));
  for (const [id, s] of Object.entries(m.states)) g.setNode(id, { width: id.length * 6.8 + 30, height: 30, final: s.kind === "final", kind: s.kind });
  for (const [from, s] of Object.entries(m.states))
    for (const [ev, t] of Object.entries(s.on ?? {}))
      g.setEdge(from, t.to, { label: ev, width: ev.length * 6 + 6, height: 12, human: t.actor === "human" }, `${from}:${ev}`);
  dagre.layout(g);
  const gi = g.graph() as { width: number; height: number };
  return {
    width: Math.ceil(gi.width), height: Math.ceil(gi.height),
    nodes: g.nodes().map((id) => { const n = g.node(id) as any; return { id, x: n.x, y: n.y, w: n.width, h: n.height, final: n.final, kind: n.kind }; }),
    edges: g.edges().map((e) => { const d = g.edge(e) as any; return { from: e.v, to: e.w, ev: d.label, human: !!d.human, x: d.x, y: d.y, points: d.points.map((p: any) => [Math.round(p.x * 10) / 10, Math.round(p.y * 10) / 10]) }; }),
  };
}

const machines = Object.values(latest).map((m) => ({ ...m, layout: { TB: layout(m, "TB"), LR: layout(m, "LR") }, skill: renderSkill(m) }));
const out = `// Generated by docs/ui-v3/build-data.ts from ${base} on ${new Date().toISOString()}. Real runs and machines.\nwindow.DATA = ${JSON.stringify({ runs, machines, capturedAt: new Date().toISOString() })};\n`;
await Bun.write(new URL("./prototype/data.js", import.meta.url), out);
console.log(`runs ${runs.length}, machines ${machines.length}, ${out.length} bytes`);
