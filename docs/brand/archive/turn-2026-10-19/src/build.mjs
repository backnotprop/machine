// ---------- React mark for the sidebar ----------
{
  const raw = hero({ pal: PAL.ui, gap: 1.8 });
  const masks = [...raw.matchAll(/<mask id="([^"]+)"[^>]*>(.*?)<\/mask>/g)].map(m => ({ id: m[1], ds: [...m[2].matchAll(/<path d="([^"]+)" fill="#000"/g)].map(x => x[1]) }));
  const groups = [...raw.matchAll(/<g(?: mask="url\(#([^)]+)\)")?>(.*?)<\/g>/g)].map(g => ({ m: g[1] ? masks.findIndex(k => k.id === g[1]) : -1, fs: [...g[2].matchAll(/<path d="([^"]+)" fill="([^"]+)"\/>/g)].map(x => [x[1], x[2]]) }));
  const sw = (raw.match(/stroke-width="([\d.]+)"/) || [])[1];
  const tsx = `// Turn, the machine mark: three states on a path that turns a corner, the corner state lit.
// Generated by docs/brand/final/src/build.mjs (ui palette, 1.8-unit seams for 18-24 px). Do not edit by hand.
import { useId } from "react";

// Cut-outs: each painted group is masked by the shapes in front of it, which opens a seam between blocks.
const CUTS: string[][] = ${JSON.stringify(masks.map(m => m.ds))};
// Painted groups in back-to-front order: [cut index or -1, [path, fill][]].
const GROUPS: [number, [string, string][]][] = ${JSON.stringify(groups.map(g => [g.m, g.fs]))};

export function Mark({ size = 20 }: { size?: number }) {
  const id = "mk" + useId().replace(/[^a-zA-Z0-9_-]/g, "");
  return (
    <svg width={size} height={size} viewBox="4 4 56 56" aria-hidden="true" focusable="false" style={{ display: "block", flex: "none", width: size, height: size }}>
      <defs>
        {CUTS.map((ds, i) => (
          <mask key={i} id={\`\${id}m\${i}\`} maskUnits="userSpaceOnUse" x="-8" y="-8" width="80" height="80">
            <rect x="-8" y="-8" width="80" height="80" fill="#fff" />
            {ds.map((d, j) => <path key={j} d={d} fill="#000" stroke="#000" strokeWidth={${sw}} strokeLinejoin="round" />)}
          </mask>
        ))}
      </defs>
      {GROUPS.map(([m, fs], i) => (
        <g key={i} mask={m >= 0 ? \`url(#\${id}m\${m})\` : undefined}>
          {fs.map(([d, fill], j) => <path key={j} d={d} fill={fill} />)}
        </g>
      ))}
    </svg>
  );
}
`;
  writeFileSync(`${ROOT}/src/ui/mark.tsx`, tsx);
}

